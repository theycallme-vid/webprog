    <p>Sosok itu adalah penjaga danau.

Ia tampak seperti wanita bercahaya dengan rambut panjang berkilau seperti air.
“Anak manusia, mengapa kau datang ke tempat yang dilindungi ini?” tanyanya dengan suara lembut.
Raka gemetar, tetapi ia berkata jujur.
“Aku hanya ingin tahu apakah danau ini benar-benar berbahaya.”
Penjaga danau tersenyum.
“Danau ini tidak berbahaya. Namun manusia sering merusak alam. Karena itu tempat ini disembunyikan.”
Raka menunduk.“Aku berjanji tidak akan merusaknya.”
Melihat ketulusan hati Raka, penjaga danau memberinya sebuah pesan.
“Jika manusia menjaga alam, maka alam akan menjaga manusia.”</p>

